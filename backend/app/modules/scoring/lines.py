def assign_solution_line(major: str, mid: str = "") -> tuple[str, float, str, str]:
    """行业 → 方案线。

    优先级：先查企查查行业中类（更细），再查国标行业大类，都未命中则兜底。
    返回 (方案线, 价值系数, 典型方案, 领域关键词)。
    """
    line = MID2LINE.get((mid or "").strip()) or MAJOR2LINE.get((major or "").strip()) or FALLBACK_LINE
    coefficient, typical, keywords = LINE_INFO.get(line, (2.0, "专线·宽带·移动办公", "服务|贸易"))
    return line, coefficient, typical, keywords


def solution_catalog() -> list[dict]:
    """返回 16 条方案线的目录（供前端筛选/展示）。"""
    catalog = [
        {
            "line": name,
            "coefficient": info[0],
            "typical": info[1],
            "keywords": info[2],
        }
        for name, info in LINE_INFO.items()
    ]
    catalog.sort(key=lambda item: item["coefficient"], reverse=True)
    return catalog
